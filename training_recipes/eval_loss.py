def main() -> None:
    dist.init_process_group(backend="nccl")
    rank = int(os.environ["LOCAL_RANK"])
    world_size = int(os.environ["WORLD_SIZE"])
    assert world_size == 1, "evaluation is single-process"
    torch.cuda.set_device(rank)
    device = torch.device("cuda", rank)
    which = os.environ.get("FX2T_EVAL_CONFIG", "quantized")
    init = os.environ.get("FX2T_EVAL_INIT", "models/6m-q4-fp32.tch")
    data_dir = os.environ.get("FX2T_DATA_DIR", "data")
    max_tokens = int(os.environ.get("FX2T_EVAL_MAX_TOKENS", "0"))
    out_path = os.environ.get("FX2T_EVAL_OUT", "out/eval.json")

    builders = {
        # "quantized" honours the Stage-2 variant switches (defaults = upstream's shipped model)
        "quantized": lambda: build_quantized(activations=os.environ.get("FX2T_EVAL_ACT", "1") == "1",
                                             emb_bits=int(os.environ.get("FX2T_EVAL_EMB_BITS", "4"))),
        "weights-only": lambda: build_quantized(weights=True, activations=False),
        "activations-only": lambda: build_quantized(weights=False, activations=True),
        "unquantized": lambda: build_unquantized(),
        "8m": lambda: build_unquantized(16, 192, 768, 3),
        "10m": lambda: build_unquantized(12, 256, 1024, 4),
    }
    raw_model = builders[which]().to(device)
    sd = {k.removeprefix("_orig_mod."): v for k, v in torch.load(init).items()}   # 8m.tch is torch.compile-wrapped
    if which in ("weights-only", "activations-only"):
        # the cooldown checkpoint carries scales for both sides; the side switched off has no module
        res = raw_model.load_state_dict(sd, strict=False)
        assert not res.missing_keys, res.missing_keys
        assert all(k.endswith(".scale") for k in res.unexpected_keys), res.unexpected_keys
        print(f"eval: {which}: {len(res.unexpected_keys)} quantizer scales dropped", flush=True)
    else:
        raw_model.load_state_dict(sd)
    model = DDP(raw_model)
    model.eval()
    data = CollatedArticlesDataLoader(
        tokens_filename=f"{data_dir}/ppmd-bytes.uint8",
        priors_filename=f"{data_dir}/ppmd-probs.float16",
        article_boundaries_filename=f"{data_dir}/article-boundaries.int32",
        mmap=True, epochs=1, micro_batch_tokens=2**17, gradient_accumulation_steps=1,
        max_article_tokens=2**17, max_merge_tokens=None, device=device, rank=rank, world_size=world_size,
    )
    print(f"eval: {which} config, checkpoint {init}, data {data_dir}, max tokens {max_tokens or 'all'}", flush=True)
    total_loss = 0.0
    total_tokens = 0
    t0 = time.time()
    with torch.inference_mode():
        for batch in data:
            for mb in batch.micro_batches:
                loss = model(input_tokens=mb.input_tokens, priors=mb.priors, loss_mask=mb.loss_mask,
                             output_tokens=mb.output_tokens, cumulative_sequence_lengths=mb.cumulative_sequence_lengths,
                             override_window_size=None)
                total_loss += float(loss.detach())
                total_tokens += int(mb.loss_mask.long().sum())
            if total_tokens and (total_tokens // 2**17) % 64 == 0:
                print(f"  {total_tokens:,} tokens  {total_loss / total_tokens:.6f} nats/token  "
                      f"{total_tokens / (time.time() - t0):,.0f} tok/s", flush=True)
            if max_tokens and total_tokens >= max_tokens:
                break
    nats = total_loss / max(1, total_tokens)
    rec = {"config": os.environ.get("FX2T_EVAL_NAME", which), "checkpoint": init, "tokens": total_tokens, "nats_per_token": nats,
           "projected_payload_bytes_at_1to1": nats * TOKENS_IN_STREAM / math.log(2) / 8,
           "seconds": time.time() - t0}
    print(json.dumps(rec, indent=1), flush=True)
    makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "a") as f:
        f.write(json.dumps(rec) + "\n")
    dist.destroy_process_group()
    # Exit without running C++ static destructors: on torch 2.12.1+cu130 the process aborted AFTER
    # all results were written ("terminate called without an active exception", SIGABRT, pod
    # lqg8sdsdneh6qp 2026-10-05 -- 1 of 3 real runs), and the non-zero exit cost the whole pipeline.
    sys.stdout.flush(); sys.stderr.flush()
    os._exit(0)


if __name__ == "__main__":
    main()
