"""Evaluate a checkpoint's next-byte loss on the real training set -- forward only, no training.

GENERATED by v16/trackC/pod from upstream training_recipes (fx2-cmix-transformer-v1 @ 83f2603): the
two TransformerConfig blocks below are copied VERBATIM -- the quantized one from cooldown.py, the
unquantized one from train_6m.py -- so each checkpoint is evaluated in exactly the configuration it
was trained in.

What it is for: the transformer's loss is ~97% of the payload (measured: 0.911403 nats/token
in-stream vs 0.886615 for the whole compressor), so
    loss(6m.tch, unquantized) - loss(6m-q4-fp32.tch, quantized)
is the quantization penalty in nats/token, and x 586,459,020 / ln 2 / 8 is what it costs in bytes
of payload. That number is the ceiling of what any better quantization could recover.

env: FX2T_EVAL_CONFIG   quantized | unquantized
     FX2T_EVAL_INIT     checkpoint path
     FX2T_DATA_DIR      (data)
     FX2T_EVAL_MAX_TOKENS  stop after this many scored tokens (0 = the whole stream). The loader
                           visits articles in a random order, so a prefix is a random sample.
     FX2T_EVAL_OUT      json file to append the result to (out/eval.json)
"""
import json
import math
import os
from dataclasses import replace
import sys
import time
from os import makedirs

import torch
from torch.nn.parallel import DistributedDataParallel as DDP
import torch.distributed as dist

from pysrc.model import Transformer, TransformerConfig, MatmulQuantization
from pysrc.quantization import Quantization
from pysrc.data import CollatedArticlesDataLoader

TOKENS_IN_STREAM = 586_459_020


def build_quantized(weights: bool = True, activations: bool = True, emb_bits: int = 4) -> Transformer:
    """weights=False / activations=False switch one side of the quantization off (Stage 1a of
    PRIZE-MODEL-PLAN: where does the 3.06 MB penalty sit?). Both True = upstream's cooldown model."""
    quantization_block_size: int | None = None

    weight_quantization = Quantization(
        buckets=15,
        block_size=quantization_block_size,
        scale_dtype=torch.bfloat16,
        arithmetic_dtype=torch.float32,
        scale_init="scaled_max",
        epsilon=None,
    )
    activation_quantization = Quantization(
        buckets=256,
        block_size=quantization_block_size,
        scale_dtype=torch.bfloat16,
        arithmetic_dtype=torch.float32,
        scale_init="scaled_mean",
        epsilon=None,
    )
    embedding_quantization = weight_quantization if emb_bits == 4 else replace(weight_quantization, buckets=256)
    if not weights:
        weight_quantization = None
        embedding_quantization = None
    if not activations:
        activation_quantization = None
    matmul_quantization = MatmulQuantization(
        weight=weight_quantization, activation=activation_quantization
    )

    raw_model: Transformer = Transformer(
        TransformerConfig(
            vocabulary_size=205,
            prior_embedding=True,
            prior_logit_mixing=False,
            max_variable_sequence_length=None,
            n_layers=12,
            attention_weight_sharing_pattern=list(range(12)),
            mlp_weight_sharing_pattern=list(range(12)),
            d_model=192,
            kimi_linear=[True, True, True, False] * 3,
            window_size=1024,
            window_size_multipliers=None,
            n_query_heads=3,
            n_key_value_heads=3,
            d_head=64,
            d_mla=None,
            rope_base=10_000,
            half_truncate_rope=False,
            query_key_norm=True,
            query_key_norm_gain=False,
            kimi_linear_d_head=64,
            kimi_linear_n_heads=3,
            kimi_linear_convolution_size=4,
            value_embedding_pattern=None,
            prior_value_embedding=False,
            attention_scale=None,
            d_mlp=768,
            activation_function="relu_squared",
            embedding_norm=True,
            prior_embedding_norm=True,
            skip_connections=True,
            token_embedding_connections=True,
            prior_embedding_connections=False,
            dropout=0.0,
            logit_softcap=15.0,
            prior_logprob_cap=-12.0,
            prior_embedding_on_logprobs=False,
            gradient_checkpointing=True,
            embedding_init="normal",
            prior_embedding_init="normal",
            up_init="kaiming_uniform",
            down_init="kaiming_uniform",
            unembedding_init="kaiming_uniform",
            convolution_init="kaiming_uniform",
            logit_mixing_head_init="zero",
            activation_dtype=torch.float32,
            attention_dtype=torch.float32,
            logit_dtype=torch.float32,
            weight_dtype=torch.float32,
            mlp_quantization=matmul_quantization,
            attention_full_rank_quantization=matmul_quantization,
            attention_low_rank_quantization=matmul_quantization,
            qkv_quantization=activation_quantization,
            kimi_linear_full_rank_quantization=matmul_quantization,
            kimi_linear_low_rank_quantization=matmul_quantization,
            kimi_linear_beta_projection_quantization=None,
            kimi_linear_convolution_quantization=None,
            embedding_quantization=embedding_quantization,
            prior_embedding_quantization=matmul_quantization,
            unembedding_quantization=matmul_quantization,
            logit_mixing_head_quantization=None,
            adamw_quantization_scales=True,
            attention_implementation="flex_attention",
        )
    )

    return raw_model


